// Reproducible evaluation. Run: node scripts/evaluate.js  → writes results/metrics.md and results/metrics.json
const fs = require('fs');
const path = require('path');
const S = require('../js/sim.js');

const TRAIN = S.range(1, 10);      // seeds used by the optimiser
const TEST = S.range(101, 130);    // unseen seeds for the out-of-sample check
const pctS = (x) => (x >= 0 ? '+' : '') + x.toFixed(1) + '%';
const inr = (x) => '₹' + Math.round(x).toLocaleString('en-IN');

const by = {}; const optRows = [];
for (const cat of Object.keys(S.CATEGORIES)) {
  const o = S.optimizeCategory(cat, { seeds: TRAIN });
  by[cat] = o.best.tiers;
  optRows.push(`| ${cat} | ${Math.round(o.best.tiers.d2 * 100)} / ${Math.round(o.best.tiers.d1 * 100)} / ${Math.round(o.best.tiers.d0 * 100)} % | ${inr(o.fixed.margin)} → ${inr(o.best.margin)} | ${Math.round(o.fixed.wasted)} → ${Math.round(o.best.wasted)} |`);
}
const policies = [
  ['Naïve 20 / 40 / 50 %', S.DEFAULT_MARKDOWN],
  ['Gentle 0 / 20 / 40 %', { name: 'gentle', tiers: { d2: 0, d1: 0.2, d0: 0.4 } }],
  ['Optimised per category', { name: 'opt', tiers: { d2: 0, d1: 0, d0: 0 }, byCategory: by }],
];
const json = { trainSeeds: TRAIN, testSeeds: TEST, optimised: by, results: {} };
let md = `# Evaluation results\n\nGenerated by \`node scripts/evaluate.js\` on ${new Date().toISOString().slice(0, 10)}. Synthetic data from the simulator. Default parameters (overstock 1.2×, shopper response 1.0×).\n\n`;
for (const [label, seeds] of [['Seeds 1–10 (used by the optimiser)', TRAIN], ['Seeds 101–130 (never seen by the optimiser)', TEST]]) {
  md += `## ${label}\n\n| Policy | Units wasted (mean) | Waste rate | Waste reduction | Revenue | Margin | Margin change (paired mean ± sd) | Lost sales |\n|---|---|---|---|---|---|---|---|\n`;
  const fx = S.multiSeed({ policy: S.FIXED }, seeds);
  md += `| Fixed price | ${fx.wasted.mean.toFixed(1)} | ${(fx.wastePct.mean * 100).toFixed(1)}% | — | ${inr(fx.revenue.mean)} | ${inr(fx.margin.mean)} | — | ${fx.lostSales.mean.toFixed(0)} |\n`;
  for (const [name, pol] of policies) {
    const c = S.compare(pol, {}, seeds);
    md += `| ${name} | ${c.policy.wasted.mean.toFixed(1)} | ${(c.policy.wastePct.mean * 100).toFixed(1)}% | ${c.wasteReductionPct.toFixed(1)}% | ${inr(c.policy.revenue.mean)} | ${inr(c.policy.margin.mean)} | ${pctS(c.marginChangePct)} (${inr(c.marginChange.mean)} ± ${inr(c.marginChange.sd)}) | ${c.policy.lostSales.mean.toFixed(0)} |\n`;
    json.results[label + ' | ' + name] = { wasteReductionPct: c.wasteReductionPct, marginChangePct: c.marginChangePct, marginChange: c.marginChange };
  }
  md += '\n';
}
md += `## Optimised rule per category (grid search, 120 monotone rules × 10 seeds)\n\n| Category | Best rule (2 d / 1 d / last day) | Margin: fixed → best | Units wasted: fixed → best |\n|---|---|---|---|\n${optRows.join('\n')}\n\n`;
md += `## Sensitivity: optimised rule vs fixed price (seeds 1–10)\n\n| Shopper response \\ Overstock | 1.1× | 1.2× | 1.3× |\n|---|---|---|---|\n`;
for (const r of [0.5, 1, 1.5]) {
  md += `| ${r}× |`;
  for (const o of [1.1, 1.2, 1.3]) {
    const c = S.compare(policies[2][1], { params: { responseMult: r, overstock: o } }, TRAIN);
    md += ` waste −${c.wasteReductionPct.toFixed(0)}%, margin ${pctS(c.marginChangePct)} |`;
  }
  md += '\n';
}
md += `\nNote: the sensitivity table reuses the rule optimised at base settings, so it tests how well that rule holds up when the assumptions are wrong.\n`;
fs.mkdirSync(path.join(__dirname, '..', 'results'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'results', 'metrics.md'), md);
fs.writeFileSync(path.join(__dirname, '..', 'results', 'metrics.json'), JSON.stringify(json, null, 2));
console.log(md);
